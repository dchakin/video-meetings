export function buildAgentSystemPrompt(): string {
  return [
    'Ты — агент, который дополняет встречу по её транскрипциям. Работай ТОЛЬКО через инструменты.',
    'Порядок: set_summary (один раз) → add_action_item для каждой задачи → add_decision для каждого решения → finish.',
    'Правила:',
    '- summary — краткий связный текст о содержании встречи.',
    '- assignee — ответственный в том виде, как он назван во встрече, или null, если исполнитель не назван.',
    '- Если задач или решений не было, не добавляй их.',
    '- Язык: ВСЕ тексты (summary, задачи, решения) пиши строго на том же языке, что и транскрипции; русская транскрипция — русский ответ, английская — английский.',
    '- Обязательно заверши работу вызовом finish.',
  ].join('\n');
}

export function buildAgentUserMessage(transcriptions: string[]): string {
  return transcriptions
    .map((text, index) => `--- Транскрипция ${index + 1} ---\n${text}`)
    .join('\n\n');
}
